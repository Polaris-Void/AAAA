#!/usr/bin/env python3
"""Regenerate src/payloads.rs from the scripts in payloads/.

v3.1.1 Defender-clean model: the launcher NO LONGER embeds payload bytes
and no longer writes scripts to %TEMP%. It executes the real files from
the payloads/ folder that ships next to the executable, and verifies every
byte against the sha256 pins in this table before each run. That removes
the write-script-then-execute dropper pattern Windows Defender heuristics
flag, while keeping full tamper evidence.

After editing any script in payloads/, run this once:

    python tools/gen_payloads.py

It rewrites src/payloads.rs (resid -> on-disk file -> sha256 pin) and
prints the summary. Keep the resid names in sync with src/data.rs.
"""
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAYLOAD_DIR = os.path.join(ROOT, "payloads")
OUT = os.path.join(ROOT, "src", "payloads.rs")

# Pin-table order (resid -> on-disk file name). Keep in sync with src/data.rs.
ORDER = [
    ("NCSI_DISABLE", "NCSI_DISABLE.reg"),
    ("NCSI_ENABLE", "NCSI_ENABLE.reg"),
    ("NCSI_RESTART", "NCSI_RESTART.bat"),
    ("USERBACKUP", "USERBACKUP.bat"),
    ("USERRESTORE", "USERRESTORE.bat"),
    ("SPOT_HIDE", "SPOT_HIDE.reg"),
    ("SPOT_SHOW", "SPOT_SHOW.reg"),
    ("DRVBACKUP", "DRVBACKUP.bat"),
    ("DRVRESTORE", "DRVRESTORE.bat"),
    ("DISPRESTORE", "DISPRESTORE.bat"),
    ("DISPBACKUP_PS", "DISPBACKUP_PS.ps1"),
    ("USB_TOOL", "USB_TOOL.bat"),
    ("DNSRESET_PS", "DNSRESET_PS.ps1"),
    ("IMGREN", "IMGREN.bat"),
    ("VIDREN", "VIDREN.bat"),
    ("TREE_PS", "TREE_PS.ps1"),
    ("SHA256_PS", "SHA256_PS.ps1"),
    ("UNPACK", "UNPACK.bat"),
    ("EXPLORER_SETTINGS", "EXPLORER_SETTINGS.bat"),
    ("USB_ICO", "USB_ICO.ico"),
]


def rust_sha(data: bytes) -> str:
    h = hashlib.sha256(data).digest()
    lines = []
    for i in range(0, len(h), 8):
        lines.append("            " + ", ".join(f"0x{b:02x}" for b in h[i : i + 8]) + ",")
    return "\n".join(lines)


def main() -> int:
    out = []
    out.append("//! AUTO-GENERATED by tools/gen_payloads.py - do not edit by hand.")
    out.append("//! Edit the scripts in payloads/ and regenerate instead.")
    out.append("//!")
    out.append("//! The payload pin table (v3.1.1 Defender-clean model): the launcher")
    out.append("//! executes the REAL files from the payloads/ folder next to the")
    out.append("//! executable and verifies every byte against these sha256 pins at")
    out.append("//! boot AND right before each run. No payload bytes are embedded,")
    out.append("//! nothing is ever written to %TEMP% - the write-then-execute dropper")
    out.append("//! pattern Windows Defender heuristics flag cannot occur by design.")
    out.append("")
    out.append("pub struct Payload {")
    out.append("    pub resid: &'static str,")
    out.append("    /// The real file inside the payloads/ folder next to the executable.")
    out.append("    pub file: &'static str,")
    out.append("    pub sha256: [u8; 32],")
    out.append("}")
    out.append("")
    out.append("impl Payload {")
    out.append("    /// The pin as a lowercase hex string (log + comparison helper).")
    out.append("    pub fn sha256_str(&self) -> String {")
    out.append("        let mut s = String::with_capacity(64);")
    out.append("        for b in &self.sha256 {")
    out.append("            s.push_str(&format!(\"{b:02x}\"));")
    out.append("        }")
    out.append("        s")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("pub const PAYLOADS: &[Payload] = &[")

    used = set()
    total = 0
    for resid, fname in ORDER:
        path = os.path.join(PAYLOAD_DIR, fname)
        if not os.path.exists(path):
            print(f"ERROR: missing payload file {path}", file=sys.stderr)
            return 1
        with open(path, "rb") as f:
            data = f.read()
        used.add(resid)
        total += len(data)
        out.append("    Payload {")
        out.append(f'        resid: "{resid}",')
        out.append(f'        file: "{fname}",')
        out.append("        sha256: [")
        out.append(rust_sha(data))
        out.append("        ],")
        out.append("    },")
    out.append("];")
    out.append("")
    out.append("/// Look up a payload pin by resource id.")
    out.append("pub fn payload(resid: &str) -> Option<&'static Payload> {")
    out.append("    PAYLOADS.iter().find(|p| p.resid == resid)")
    out.append("}")
    out.append("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"regenerated {os.path.relpath(OUT, ROOT)}: {len(used)} pins, {total} bytes on disk")
    for resid, fname in ORDER:
        print(f"  {resid:<18} -> {fname}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
